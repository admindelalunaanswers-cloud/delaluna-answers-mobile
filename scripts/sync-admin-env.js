#!/usr/bin/env node
/**
 * Generates admin-web/.env from the repo-root env snapshot for one project.
 *
 * The admin dashboard picks its Firebase project at *build* time — there is
 * deliberately no runtime switcher (see admin-web/src/lib/firebase.ts). So the
 * bundle and the deploy target have to be chosen together, or you get the worst
 * possible outcome: a production URL serving a bundle wired to test, with the
 * header badge quietly reading "○ Test". The deploy:* scripts in
 * admin-web/package.json run this first so the pairing cannot drift.
 *
 * Only the six FIREBASE_* values are copied. env.{test,prod}.local also hold
 * REVENUECAT_KEY_V1 / V2 and GOOGLE_API_KEY, and everything Vite inlines under a
 * VITE_ prefix ships readable inside the deployed bundle — so a blanket copy
 * would publish secret keys to a public URL. The allowlist below is the control;
 * do not replace it with a prefix match over the whole file.
 *
 * Usage: node ./scripts/sync-admin-env.js <test|prod>
 */

const fs = require('node:fs');
const path = require('node:path');

const TARGETS = {
  test: { file: 'env.test.local', projectId: 'delaluna-answers-test' },
  prod: { file: 'env.prod.local', projectId: 'delaluna-answers' },
};

const KEYS = [
  'FIREBASE_API_KEY',
  'FIREBASE_AUTH_DOMAIN',
  'FIREBASE_PROJECT_ID',
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID',
  'FIREBASE_APP_ID',
];

const target = TARGETS[process.argv[2]];
if (!target) {
  console.error('[sync-admin-env] Usage: node ./scripts/sync-admin-env.js <test|prod>');
  process.exit(1);
}

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, target.file);

if (!fs.existsSync(sourcePath)) {
  console.error(`[sync-admin-env] Missing ${target.file} at the repo root.`);
  process.exit(1);
}

const source = fs.readFileSync(sourcePath, 'utf8');
const values = new Map();
for (const line of source.split('\n')) {
  const match = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
  if (match) values.set(match[1], match[2].trim());
}

const missing = KEYS.filter((key) => !values.get(key));
if (missing.length > 0) {
  console.error(`[sync-admin-env] ${target.file} is missing: ${missing.join(', ')}`);
  process.exit(1);
}

// A snapshot that has drifted is the one failure this script exists to catch.
// Trusting the file's own project id would defeat the point of naming a target.
const found = values.get('FIREBASE_PROJECT_ID');
if (found !== target.projectId) {
  console.error(
    `[sync-admin-env] ${target.file} holds FIREBASE_PROJECT_ID=${found}, expected ${target.projectId}. Refusing to write.`,
  );
  process.exit(1);
}

const body = [
  `# Auto-generated by scripts/sync-admin-env.js from ../${target.file}.`,
  `# Target: ${target.projectId}. Do not edit by hand — rerun the script instead.`,
  '#',
  '# Not secret: Firebase web config is public by design and these same values',
  '# ship in every installed copy of the mobile app. Access is controlled by the',
  '# `admin` custom auth claim and the Firestore rules.',
  '',
  ...KEYS.map((key) => `VITE_${key}=${values.get(key)}`),
  '',
].join('\n');

fs.writeFileSync(path.join(root, 'admin-web', '.env'), body);
console.log(`[sync-admin-env] admin-web/.env → ${target.projectId} (from ${target.file})`);
